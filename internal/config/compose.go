package config

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// GenerateCompose writes a docker-compose.yml for the given profile+environment
// to ~/.stackr/<profile>/<env>/docker-compose.yml
func GenerateCompose(profile Profile, envName string) (string, error) {
	env := findEnv(profile, envName)
	if env == nil {
		return "", fmt.Errorf("environment %q not found in profile %q", envName, profile.Name)
	}

	// Port-forward-only environments have no services — skip compose generation
	if len(env.Services) == 0 {
		return "", nil
	}

	dir := filepath.Join(ProfileDir(profile.Name), envName)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString("# Generated by Stackr — do not edit manually\n")
	b.WriteString(fmt.Sprintf("# Profile: %s  |  Environment: %s\n\n", profile.Name, envName))
	b.WriteString("services:\n")

	// collect named volumes
	namedVolumes := map[string]bool{}
	networkNames := map[string]bool{}
	netName := fmt.Sprintf("%s-%s-network", profile.Name, envName)
	networkNames[netName] = true

	for _, svc := range env.Services {
		compName := svc.ComposeName()
		b.WriteString(fmt.Sprintf("  %s:\n", compName))
		b.WriteString(fmt.Sprintf("    image: %s\n", svc.FullImage()))
		b.WriteString(fmt.Sprintf("    container_name: stackr-%s-%s-%s\n", profile.Name, envName, compName))

		if len(svc.Ports) > 0 {
			b.WriteString("    ports:\n")
			for _, p := range svc.Ports {
				b.WriteString(fmt.Sprintf("      - \"%s\"\n", p.String()))
			}
		}

		if len(svc.EnvVars) > 0 {
			b.WriteString("    environment:\n")
			for _, e := range svc.EnvVars {
				b.WriteString(fmt.Sprintf("      %s: %s\n", e.Key, e.Value))
			}
		}

		if len(svc.Volumes) > 0 {
			b.WriteString("    volumes:\n")
			for _, v := range svc.Volumes {
		if v.Named {
				volName := v.Source
				if volName == "" {
					volName = fmt.Sprintf("%s_%s_%s_data", profile.Name, envName, compName)
				}
				b.WriteString(fmt.Sprintf("      - %s:%s\n", volName, v.Target))
				namedVolumes[volName] = true
				} else {
					b.WriteString(fmt.Sprintf("      - %s:%s\n", v.Source, v.Target))
				}
			}
		}

		if svc.HealthCheck != nil {
			b.WriteString("    healthcheck:\n")
			b.WriteString(fmt.Sprintf("      test: [\"%s\"]\n", svc.HealthCheck.Test))
			b.WriteString(fmt.Sprintf("      interval: %s\n", svc.HealthCheck.Interval))
			b.WriteString(fmt.Sprintf("      timeout: %s\n", svc.HealthCheck.Timeout))
			b.WriteString(fmt.Sprintf("      retries: %d\n", svc.HealthCheck.Retries))
		}

		if len(svc.DependsOn) > 0 {
			b.WriteString("    depends_on:\n")
			for _, dep := range svc.DependsOn {
				b.WriteString(fmt.Sprintf("      - %s\n", dep))
			}
		}

		restart := svc.Restart
		if restart == "" {
			restart = "unless-stopped"
		}
		b.WriteString(fmt.Sprintf("    restart: %s\n", restart))

		b.WriteString("    networks:\n")
		b.WriteString(fmt.Sprintf("      - %s\n", netName))
		b.WriteString("\n")
	}

	// Named volumes section
	if len(namedVolumes) > 0 {
		b.WriteString("volumes:\n")
		for vol := range namedVolumes {
			b.WriteString(fmt.Sprintf("  %s:\n    driver: local\n", vol))
		}
		b.WriteString("\n")
	}

	// Networks section
	b.WriteString("networks:\n")
	for net := range networkNames {
		b.WriteString(fmt.Sprintf("  %s:\n    driver: bridge\n", net))
	}

	outPath := filepath.Join(dir, "docker-compose.yml")
	if err := os.WriteFile(outPath, []byte(b.String()), 0644); err != nil {
		return "", err
	}
	return outPath, nil
}

func findEnv(profile Profile, envName string) *Environment {
	for i := range profile.Environments {
		if profile.Environments[i].Name == envName {
			return &profile.Environments[i]
		}
	}
	return nil
}
